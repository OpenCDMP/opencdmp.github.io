import fs from 'fs';
import path from 'path';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

/**
 * The documentation sidebar.
 *
 * The top level and the administration guide are written by hand, so that the
 * admin pages follow the groups of the application's admin menu. The other
 * sections are generated from their folders, whose `_category_.json` files set
 * the labels and order inside them. Doc ids are file paths without extension.
 */

type Item = Record<string, unknown> & {position?: number; source: string};
type SidebarItems = Extract<SidebarsConfig[string], unknown[]>;

const DOCS_DIR = path.join(__dirname, 'docs');

function frontMatter(file: string): Record<string, string> {
  const text = fs.readFileSync(file, 'utf8');
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const result: Record<string, string> = {};
  for (const line of match?.[1].split(/\r?\n/) ?? []) {
    const pair = /^([\w-]+):\s*(.*)$/.exec(line);
    if (pair) result[pair[1]] = pair[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  const heading = /^#\s+(.+)$/m.exec(text.slice(match?.[0].length ?? 0));
  if (heading && result.title === undefined) result.title = heading[1].trim();
  return result;
}

function byPosition(items: Item[]): Record<string, unknown>[] {
  return [...items]
    .sort((a, b) => (a.position ?? Infinity) - (b.position ?? Infinity) || a.source.localeCompare(b.source))
    .map(({position, source, ...item}) => item);
}

/**
 * Generates the items of a docs folder the way an autogenerated sidebar does
 * (`_category_.json` metadata, `sidebar_position`, index docs as category
 * links), and leaves out the folder's own index doc. An autogenerated item
 * would list that doc again next to the category it already links.
 */
function folderItems(dir: string): SidebarItems {
  return byPosition(folderChildren(dir).filter((item) => !isIndexDoc(item, dir))) as SidebarItems;
}

function isIndexDoc(item: Item, dir: string): boolean {
  return item.type === 'doc' && /^(index|readme)$/i.test(path.posix.basename(item.id as string)) && path.posix.dirname(item.id as string) === dir;
}

function folderChildren(dir: string): Item[] {
  const items: Item[] = [];
  for (const entry of fs.readdirSync(path.join(DOCS_DIR, dir), {withFileTypes: true})) {
    if (entry.name.startsWith('_')) continue;
    const rel = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) {
      const category = categoryItem(rel, entry.name);
      if (category) items.push(category);
    } else if (/\.mdx?$/.test(entry.name)) {
      const fm = frontMatter(path.join(DOCS_DIR, rel));
      items.push({
        type: 'doc',
        id: rel.replace(/\.mdx?$/, ''),
        position: fm.sidebar_position !== undefined ? Number(fm.sidebar_position) : undefined,
        source: entry.name,
        ...(fm.sidebar_label !== undefined && {label: fm.sidebar_label}),
        ...(fm.sidebar_class_name !== undefined && {className: fm.sidebar_class_name}),
      });
    }
  }
  return items;
}

function categoryItem(dir: string, name: string): Item | undefined {
  const children = folderChildren(dir);
  if (children.length === 0) return undefined;
  const metaFile = path.join(DOCS_DIR, dir, '_category_.json');
  const meta = fs.existsSync(metaFile) ? JSON.parse(fs.readFileSync(metaFile, 'utf8')) : {};
  const linkedId: string | undefined =
    meta.link?.type === 'doc'
      ? path.posix.join(dir, meta.link.id)
      : meta.link === undefined
        ? (children.find((item) => isIndexDoc(item, dir) || (item.type === 'doc' && path.posix.basename(item.id as string) === name))?.id as string | undefined)
        : undefined;
  const linkedFm = linkedId ? frontMatter(path.join(DOCS_DIR, `${linkedId}.md`)) : {};
  const className = meta.className ?? linkedFm.sidebar_class_name;
  return {
    type: 'category',
    label: meta.label ?? linkedFm.sidebar_label ?? linkedFm.title ?? name,
    position: meta.position ?? (linkedFm.sidebar_position !== undefined ? Number(linkedFm.sidebar_position) : undefined),
    source: name,
    ...(meta.collapsible !== undefined && {collapsible: meta.collapsible}),
    ...(meta.collapsed !== undefined && {collapsed: meta.collapsed}),
    ...(className !== undefined && {className}),
    ...(linkedId ? {link: {type: 'doc', id: linkedId}} : meta.link ? {link: meta.link} : {}),
    items: byPosition(children.filter((item) => item.id !== linkedId)),
  };
}

